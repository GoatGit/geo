const EXISTING = ['美妆个护', '家电', '新能源汽车', '护肤品', '零食', '手机'];

function validate() {
  const names = INDUSTRIES.map((i) => i.name);
  const dup = names.filter((n, i) => names.indexOf(n) !== i);
  const overlap = names.filter((n) => EXISTING.includes(n));
  const badLayer = INDUSTRIES.flatMap((ind) => questionsFor(ind)).filter(
    (q) => !['消费功能层', '场景人群层', '品类行业层', '竞品层', '价格决策层', '渠道市场层', '风险信任层'].includes(q.layer),
  );
  const brandCount = INDUSTRIES.reduce((a, i) => a + i.brands.length, 0);
  const qCount = INDUSTRIES.length * 8;
  console.log(`行业数: ${names.length}(目标 94,合计现有 6 = 100)`);
  console.log(`品牌数: ${brandCount}(目标 564) 行业问题: ${qCount}(目标 752)`);
  console.log(`重名: ${dup.length ? dup.join(',') : '无'} 与现有重叠: ${overlap.length ? overlap.join(',') : '无'} 非法分层: ${badLayer.length}`);
  if (names.length !== 94 || dup.length || overlap.length || badLayer.length) {
    console.error('校验未通过');
    process.exit(1);
  }
  console.log('校验通过 ✓');
}

async function seed() {
  const c = new Client({ connectionString: process.env.DATABASE_URL, connectionTimeoutMillis: 15000 });
  await c.connect();
  let industriesAdded = 0, brandsAdded = 0, questionsAdded = 0, skippedExisting = 0;
  for (let sort = 0; sort < INDUSTRIES.length; sort++) {
    const ind = INDUSTRIES[sort];
    const exists = (await c.query('select id from insight_industries where name=$1', [ind.name])).rows[0];
    if (exists) { skippedExisting++; continue; }
    const ins = (await c.query(
      'insert into insight_industries (name, sort, active) values ($1,$2,true) returning id',
      [ind.name, sort + 10],
    )).rows[0];
    industriesAdded++;
    for (const [name, aliases, positioning] of ind.brands) {
      await c.query(
        'insert into insight_brands (industry_id, name, aliases, positioning, active) values ($1,$2,$3::jsonb,$4,true)',
        [ins.id, name.trim(), JSON.stringify(aliases ?? []), positioning ?? null],
      );
      brandsAdded++;
    }
    for (const q of questionsFor(ind)) {
      await c.query(
        'insert into insight_questions (industry_id, text_raw, type, layer, active) values ($1,$2,$3,$4,true)',
        [ins.id, q.text, q.type, q.layer],
      );
      questionsAdded++;
    }
  }
  console.log(`写入完成:新行业 ${industriesAdded},品牌 ${brandsAdded},问题 ${questionsAdded};已存在跳过 ${skippedExisting}`);
  const total = (await c.query('select count(*)::int n from insight_industries')).rows[0].n;
  const tb = (await c.query('select count(*)::int n from insight_brands')).rows[0].n;
  const tq = (await c.query('select count(*)::int n from insight_questions')).rows[0].n;
  console.log(`库内总计:行业 ${total} / 行业品牌 ${tb} / 行业问题 ${tq}`);
  await c.end();
}

if (process.argv.includes('--check')) validate();
else { validate(); await seed(); }
